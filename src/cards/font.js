export function glyph(char, size) {
  if (size === 3) {
    if (FONT_3x5[char]) return FONT_3x5[char];
    if (FONT_3x5[char.toUpperCase()]) return FONT_3x5[char.toUpperCase()];
    const alias = { "×": "x", "✕": "x" };
    if (alias[char] && FONT_3x5[alias[char]]) return FONT_3x5[alias[char]];
    return GLYPHS[char]?.small || FONT_3x5["?"];
  }
  if (FONT_5x7[char]) return FONT_5x7[char];
  if (FONT_5x7[char.toUpperCase()]) return FONT_5x7[char.toUpperCase()];
  const alias = { "×": "x", "✕": "x" };
  if (alias[char] && FONT_5x7[alias[char]]) return FONT_5x7[alias[char]];
  return GLYPHS[char]?.large || FONT_5x7["?"];
}

export function textWidth(text, size, scale = 1, tracking = 1) {
  const w = size === 3 ? 3 : 5;
  if (!text.length) return 0;
  return (text.length * (w + tracking) - tracking) * scale;
}

export function drawText(ctx, text, x, y, { size = 3, scale = 1, color = "#1a1a2e", tracking = 1, shadow = null } = {}) {
  const rows = size === 3 ? 5 : 7;
  const w = size === 3 ? 3 : 5;
  const step = (w + tracking) * scale;
  const str = String(text);
  if (shadow) drawText(ctx, str, x + scale, y + scale, { size, scale, color: shadow, tracking });
  for (let i = 0; i < str.length; i += 1) {
    const pattern = glyph(str[i], size);
    for (let ry = 0; ry < rows; ry += 1) {
      const row = pattern[ry] || "";
      for (let rx = 0; rx < w; rx += 1) {
        if (row[rx] !== "#") continue;
        ctx.fillStyle = color;
        ctx.fillRect(x + i * step + rx * scale, y + ry * scale, scale, scale);
      }
    }
  }
  return textWidth(str, size, scale, tracking);
}

export function fitText(ctx, text, max, size, scale, tracking = 1) {
  const w = size === 3 ? 3 : 5;
  let str = String(text);
  if (textWidth(str, size, scale, tracking) <= max) return str;
  while (str.length > 0 && textWidth(`${str}…`, size, scale, tracking) > max) str = str.slice(0, -1);
  return `${str}`;
}
